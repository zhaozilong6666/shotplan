GENERATED_MARK = "<!-- generated by scripts/kb.py"
# Phrased so the report audit's existing detector recognises these pages as
# scripted output. Otherwise the three would be compared for textual
# redundancy and flagged as near-duplicates of each other.
GENERATED_NOTE = "> 由 `scripts/kb.py` 生成，不要手改；改数据或脚本后重跑 `--write`。"

# Inline code is where this repo puts every citation. Three shapes are checked
# because each has a mechanical resolver: a path exists or it does not, a
# function is defined or it is not, an experiment id is in the ledger or it is
# not. Anything vaguer (concept words, config keys, rule names used as prose)
# produced an 86% false-positive rate in a first pass and is deliberately out
# of scope.
INLINE = re.compile(r"`([^`\n]{2,160})`")
REF_PATH = re.compile(
    r"^((?:src|docs|evals|scripts|tests|data)/[A-Za-z0-9_./-]+\.(?:py|md|json|jsonl|html|toml|ya?ml))$"
)
REF_ROOT_FILE = re.compile(r"^(?:pyproject\.toml|Makefile|Dockerfile|requirements\.lock)$")
REF_CALL = re.compile(r"^([a-z_][a-z0-9_]*(?:\.[a-z_][a-z0-9_]*)*)\(\)$")
REF_EXPERIMENT = re.compile(r"\bE(\d{2})\b")
MD_LINK = re.compile(r"\]\(([^)\s]+\.md)(?:#[^)]*)?\)")

# Callables that appear in prose as `sum()` but are not repo code. Grouped by
# where they come from, so adding one is a decision rather than a papering-over:
# builtins, stdlib (os.cpu_count), and the PromQL functions the SLI documents
# discuss as things this project deliberately does NOT do.
NOT_REPO_CALLS = {
    # builtins
    "sum", "len", "min", "max", "sorted", "range", "fsum", "any", "all", "zip",
    "map", "filter", "open", "print", "enumerate", "round", "abs", "isinstance",
    "getattr", "setattr", "format", "join", "split", "append", "items", "get",
    "keys", "values", "update", "startswith", "endswith", "lower", "upper",
    "int", "float", "str", "dict", "list", "set", "tuple", "bool",
    # stdlib
    "cpu_count",
    # PromQL
    "rate", "histogram_quantile",
}

# A path written as a range (`v1..v6-naive.json`) or a gitignored build output
# is not a citation of a committed file. Both shapes appeared as false
# positives on the first run.
RANGE_ELLIPSIS = ".."
GENERATED_PREFIXES = ("evals/out/",)

# A revisit condition has to name an observable event. These words signal the
# opposite: a promise to think about it later, which is what ADR "when to
# revisit" sections decay into.
VAGUE_TRIGGERS = ("以后", "将来", "未来", "必要时", "如果不好用", "看情况", "再说", "觉得")

KIND_LABELS = {
    "adr": "决策记录",
    "snapshot": "历史快照",
    "generated": "生成页",
    "guide": "说明",
    "portfolio": "个人材料",
}


@dataclass(frozen=True)
class Facts:
    """What one document cites, and what cites it back."""

    path: str  # repo-relative, POSIX separators
    kind: str
    paths: tuple[str, ...] = ()
    calls: tuple[str, ...] = ()
    experiments: tuple[str, ...] = ()
    links: tuple[str, ...] = ()  # resolved repo-relative md targets
    cited_by: tuple[str, ...] = ()  # experiment ids using this document as evidence


@dataclass(frozen=True)
class Issue:
    doc: str
    token: str
    kind: str  # "path" | "call" | "experiment"
    detail: str


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def classify(path: Path, text: str) -> str:
    if generator_of(text):
        return "generated"
    name = path.name
    if "adr" in path.parts:
        return "adr"
    if "portfolio" in path.parts:
        return "portfolio"
    if re.search(r"20\d{2}-\d{2}-\d{2}", name):
        return "snapshot"
    return "guide"


def measurement_anchors(doc: Facts) -> tuple[str, ...]:
    """Cited files that are themselves measurements: eval scripts and snapshots.

    Weaker than an experiment id and stronger than prose: `evals/benchmark.json`
    exists and is regenerated by a gate, so a claim leaning on it can be
    re-derived even when nobody wrote an E-number for it.
    """
    return tuple(
        p for p in doc.paths
        if p.startswith("evals/") and (p.endswith(".json") or p.endswith(".py"))
    )


def resolve_link(doc: Path, target: str) -> str | None:
    """Turn a markdown link into a repo-relative path, or None if it escapes."""
    raw = target.split("#", 1)[0].strip()
    if not raw:
        return None
    candidate = (doc.parent / raw).resolve()
    try:
        return candidate.relative_to(ROOT).as_posix()
    except ValueError:
        return None


def parse_citations(body: str) -> tuple[tuple[str, ...], tuple[str, ...], tuple[str, ...]]:
    """Paths, callables and experiment ids cited in one document's text.

    Pure text in, sorted-unique tuples out -- no filesystem, so the edge cases
    (range ellipsis, build directories, builtins) can be tested directly.
    """
    paths: list[str] = []
    calls: list[str] = []
    experiments: list[str] = []
    for token in INLINE.findall(body):
        raw = token.strip()
        if REF_PATH.match(raw) or REF_ROOT_FILE.match(raw):
            if RANGE_ELLIPSIS in raw or raw.startswith(GENERATED_PREFIXES):
                continue
            paths.append(raw)
            continue
        match = REF_CALL.match(raw)
        if match:
            name = match.group(1).rsplit(".", 1)[-1]
            if name not in NOT_REPO_CALLS:
                calls.append(name)
    for match in REF_EXPERIMENT.finditer(body):
        experiments.append(f"E{match.group(1)}")
    return (
        tuple(dict.fromkeys(paths)),
        tuple(dict.fromkeys(calls)),
        tuple(dict.fromkeys(experiments)),
    )


def read_facts(path: Path, text: str | None = None) -> Facts:
    body = text if text is not None else path.read_text(encoding="utf-8")
    paths, calls, experiments = parse_citations(body)
    links = [resolved for target in MD_LINK.findall(body) if (resolved := resolve_link(path, target))]
    return Facts(
        path=rel(path),
        kind=classify(path, body),
        paths=paths,
        calls=calls,
        experiments=experiments,
        links=tuple(dict.fromkeys(links)),
    )


def all_docs() -> list[Path]:
    """Every markdown document that participates in the knowledge base.

    The three pages this script writes are excluded: scanning last run's output
    would let a stale copy of a problem become evidence that the problem still
    exists. `docs/portfolio/` is excluded for the same reason it is excluded from
    the report audit -- job-application material is not a project record, and
    counting it here made the two reports disagree about how large the corpus is.
    """
    own = {HEALTH.name, NEXT.name, HANDOFF.name}
    found = [*ROOT.glob("*.md"), *DOCS.rglob("*.md")]
    return sorted(
        path for path in found if path.name not in own and "portfolio" not in path.parts
    )


def symbol_index() -> dict[str, str]:
    """Which file defines each symbol -- the other half of a citation.

    `defined_names` answers "does this name exist anywhere", which is enough to
    catch a citation of deleted code. Answering "what breaks if I change this
    file" needs the edge in the other direction, so the same scan keeps it.
    """
    index: dict[str, str] = {}
    for base in (SRC, ROOT / "evals", ROOT / "scripts"):
        for path in base.rglob("*.py"):
            text = path.read_text(encoding="utf-8")
            found = re.findall(r"^\s*(?:def|class)\s+([A-Za-z_][A-Za-z0-9_]*)", text, re.M)
            found += re.findall(r"^([A-Z][A-Z0-9_]{2,})\s*[:=]", text, re.M)
            for name in found:
                index.setdefault(name, rel(path))
    return index


def defined_names() -> set[str]:
    """Every function, class and module-level constant defined in this repo."""
    return set(symbol_index())


def explain(
    target: str,
    facts: list[Facts],
    decisions: list[dict[str, Any]],
    ledger: list[dict[str, Any]],
    symbols: dict[str, str],
    texts: dict[str, str],
) -> str:
    """What points at this file, and what has to be reconsidered if it changes.

    The rest of this script answers "is this document still true". This answers
    the question that comes first in practice: I am about to edit a file, which
    records does that touch? --file is the reverse edge of every citation the
    gate checks.
    """
    wanted = target.replace("\\", "/").removeprefix("./")
    basename = wanted.rsplit("/", 1)[-1]

    direct = [doc for doc in facts if wanted in doc.paths]
    # Paths in prose are anchored to a repo directory, so `constraints.py` on its
    # own is not a citation the gate checks. It is still a mention, and someone
    # asking "what depends on this" wants to see it -- labelled differently.
    mentioned = [
        doc
        for doc in facts
        if doc not in direct
        and basename
        in {token.strip().rsplit("/", 1)[-1] for token in INLINE.findall(texts.get(doc.path, ""))}
    ]
    indirect = [
        doc
        for doc in facts
        if doc not in direct
        and doc not in mentioned
        and any(symbols.get(call) == wanted for call in doc.calls)
    ]
    touching = direct + mentioned + indirect

    lines = [f"{wanted}", ""]
    if not touching:
        lines += ["没有文档引用这个路径，也没有文档引用它定义的符号。", ""]
        return "\n".join(lines)

    if direct:
        lines += [f"直接引用（{len(direct)} 份）"]
        lines += [f"  {doc.path}" for doc in direct]
        lines.append("")
    if mentioned:
        lines += [f"提到文件名（{len(mentioned)} 份，不是路径引用）"]
        lines += [f"  {doc.path}" for doc in mentioned]
        lines.append("")
    if indirect:
        lines += [f"通过符号引用（{len(indirect)} 份）"]
        for doc in indirect:
            hit = sorted({call for call in doc.calls if symbols.get(call) == wanted})
            lines.append(f"  {doc.path}（{', '.join(hit)}）")
        lines.append("")

    paths = {doc.path for doc in touching}
    related_decisions = [row for row in decisions if str(row.get("adr")) in paths]
    if related_decisions:
        lines += [f"相关决策（{len(related_decisions)} 条）"]
        for row in related_decisions:
            support = ", ".join(row.get("evidence") or []) or "无实验依据"
            lines.append(f"  {row['id']} {row['decision']}（依据 {support}）")
        lines.append("")

    cited_docs = {str(row.get("evidence")) for row in ledger if row.get("evidence")}
    related_experiments = [row for row in ledger if str(row.get("evidence")) in paths]
    if related_experiments:
        lines += [f"相关实验（{len(related_experiments)} 条）"]
        for row in related_experiments:
            lines.append(f"  {row['id']} {row['question']}（{row['verdict']}）")
        lines.append("")

    lines += [
        "改它之前：",
        "  - 引用不会失效（路径与符号仍在），但描述可能过期；`--queue` 按漂移排序",
        "  - 改了签名或行为，`make gates` 负责红；改了结论，上面那几条实验要重读",
    ]
    if cited_docs & paths:
        lines.append("  - 它（或引用它的文档）是实验证据：改了数字，证据文档要跟着更新")
    lines.append("")
    return "\n".join(lines)


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            rows.append(json.loads(line))
    return rows


def cite_issues(facts: list[Facts], names: set[str], experiment_ids: set[str]) -> list[Issue]:
    issues: list[Issue] = []
    for doc in facts:
        for cited in doc.paths:
            if not (ROOT / cited).exists():
                issues.append(Issue(doc.path, cited, "path", "路径不存在"))
        for called in doc.calls:
            if called not in names:
                issues.append(Issue(doc.path, f"{called}()", "call", "仓库内没有这个函数/类"))
        for cited in doc.experiments:
            if cited not in experiment_ids:
                issues.append(Issue(doc.path, cited, "experiment", "实验台账里没有这一条"))
    return issues


def evidence_grade(doc: Facts, verdicts: dict[str, str]) -> str:
    """How much of this document can be re-checked without reading it.

    `empirical` means a decided experiment is attached to it -- in either
    direction. A report that cites `E01` and a report that `E01` names as its
    evidence are the same relationship seen from two ends; scoring only the
    first made five measured reports look unsupported.

    `referential` means it points at code or files that exist. `narrative` means
    neither -- not an accusation, only that nothing mechanical can confirm it.
    """
    decided = {key for key, value in verdicts.items() if value in {"confirmed", "refuted", "partial"}}
    if any(item in decided for item in (*doc.experiments, *doc.cited_by)):
        return "empirical"
    if doc.paths or doc.calls:
        return "referential"
    return "narrative"


def decision_problems(rows: list[dict[str, Any]], adrs: set[str], experiment_ids: set[str]) -> list[str]:
    problems: list[str] = []
    seen: set[str] = set()
    for line_no, row in enumerate(rows, 1):
        ident = row.get("id") or f"line {line_no}"
        if ident in seen:
            problems.append(f"{ident}: 重复 id")
        seen.add(ident)
        adr = str(row.get("adr", ""))
        if adr not in adrs:
            problems.append(f"{ident}: adr 不存在 -> {adr or '<empty>'}")
        if not str(row.get("decision", "")).strip():
            problems.append(f"{ident}: decision 为空")
        triggers = row.get("breaks_if") or []
        if not isinstance(triggers, list) or not triggers:
            problems.append(f"{ident}: breaks_if 至少写一条可观测的触发条件")
            continue
        for trigger in triggers:
            if len(str(trigger).strip()) < 8:
                problems.append(f"{ident}: breaks_if 太短，无法判断 -> {trigger!r}")
        if row.get("status") not in {"active", "superseded"}:
            problems.append(f"{ident}: status 必须是 active 或 superseded")
        # Two different relations get two different fields. `evidence` supports
        # the decision, so an experiment later refuted puts it in doubt.
        # `examples` is cited as a case -- D08 points at E03 precisely because it
        # lost: that is what versioned prompts let the project notice. Lumping
        # both into `evidence` made the refutation check flag its own best
        # illustration.
        for field_name in ("evidence", "examples"):
            items = row.get(field_name) or []
            if not isinstance(items, list):
                problems.append(f"{ident}: {field_name} 必须是实验 id 列表")
                continue
            for item in items:
                if item not in experiment_ids:
                    problems.append(f"{ident}: {field_name} 引用的实验不在台账 -> {item}")
    return problems


def vague_triggers(rows: list[dict[str, Any]]) -> list[str]:
    """Soft signal: a revisit condition phrased as a feeling instead of an event."""
    found: list[str] = []
    for row in rows:
        for trigger in row.get("breaks_if") or []:
            if any(word in str(trigger) for word in VAGUE_TRIGGERS):
                found.append(f"{row.get('id')}: {trigger}")
    return found


def unused_waivers(allowed: dict[str, str], issues: list[Issue]) -> list[str]:
    """Waivers that no longer match a live issue.

    A waiver exists to name a debt, not to silence a checker forever. Once the
    citation is fixed or the document is deleted, the entry is stale and should
    go -- otherwise the allow-list grows into a second, unread corpus.
    """
    live = {f"{issue.doc}::{issue.token}" for issue in issues}
    return sorted(key for key in allowed if key not in live)


def refuted_dependencies(
    decisions: list[dict[str, Any]], verdicts: dict[str, str]
) -> list[tuple[str, str, str]]:
    """Decisions that lean on an experiment later refuted, as (decision, adr, experiment).

    The answer is a property of the decision, not of the documents that happen
    to cite the same experiment. An earlier version walked the documents and
    produced rows for unrelated decisions; nothing caught it because no decision
    had cited a refuted experiment yet.
    """
    return [
        (str(row.get("id")), str(row.get("adr")), item)
        for row in decisions
        for item in (row.get("evidence") or [])
        if verdicts.get(item) == "refuted"
    ]


def enrich(facts: list[Facts], decisions: list[dict[str, Any]], ledger: list[dict[str, Any]]) -> list[Facts]:
    """Attach the evidence relationships that live outside the prose.

    Two of them, and both were missing at first:

    1. The decision index may name the experiments behind an ADR whose own text
       does not. Without it, an ADR supported one layer up counts as "no
       evidence" and the queue says to go write what already exists.
    2. An experiment may name a document as its evidence. That is the same
       relation as the document citing the experiment, read from the other end;
       scoring only one direction made five measured reports look unsupported.
    """
    by_adr = {str(row.get("adr")): row for row in decisions}
    by_document: dict[str, list[str]] = {}
    for row in ledger:
        evidence = row.get("evidence")
        if evidence:
            by_document.setdefault(str(evidence), []).append(str(row.get("id")))
    enriched: list[Facts] = []
    for doc in facts:
        row = by_adr.get(doc.path)
        extra = tuple(str(item) for item in (row.get("evidence") or [])) if row else ()
        experiments = tuple(sorted(set(doc.experiments) | set(extra)))
        cited_by = tuple(sorted(by_document.get(doc.path, ())))
        if experiments != doc.experiments or cited_by:
            doc = replace(doc, experiments=experiments, cited_by=cited_by)
        enriched.append(doc)
    return enriched


def rule_mentions(texts: dict[str, str], codes: list[str]) -> dict[str, list[str]]:
    mentions: dict[str, list[str]] = {}
    for code in codes:
        pattern = re.compile(rf"\b{re.escape(code)}\b")
        mentions[code] = sorted(doc for doc, text in texts.items() if pattern.search(text))
    return mentions


def incoming_links(facts: list[Facts]) -> dict[str, int]:
    counter: dict[str, int] = {}
    for doc in facts:
        for target in doc.links:
            counter[target] = counter.get(target, 0) + 1
    return counter


def commit_dates() -> dict[str, str]:
    """Last commit date per path, from one `git log` walk.

    A shallow clone (GitHub Actions default is depth 1) has no history to
    compare against, so this returns empty rather than pretending every
    document is up to date. Drift only affects the local `--queue` view.
    """
    try:
        count = subprocess.run(
            ["git", "rev-list", "--count", "HEAD"],
            cwd=ROOT, capture_output=True, text=True, check=True, timeout=20,
        ).stdout.strip()
        if not count or int(count) < 2:
            return {}
        out = subprocess.run(
            ["git", "log", "--pretty=format:%cs", "--name-only", "--relative"],
            cwd=ROOT, capture_output=True, text=True, check=True, timeout=60,
        ).stdout
    except (subprocess.SubprocessError, ValueError, OSError):
        return {}
    dates: dict[str, str] = {}
    current = ""
    for line in out.splitlines():
        line = line.strip()
        if not line:
            continue
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}", line):
            current = line
        elif current:
            dates.setdefault(line, current)  # log is newest-first
    return dates


def drift_rank(facts: list[Facts], dates: dict[str, str]) -> list[tuple[int, str, str]]:
    """Documents whose cited code moved after the document did.

    Divergence, not age: a document is suspicious when the file it describes
    has commits newer than the document itself. Returns (days, doc, cited).
    """
    ranked: list[tuple[int, str, str]] = []
    for doc in facts:
        doc_date = dates.get(doc.path)
        if not doc_date:
            continue
        newest: tuple[int, str] | None = None
        for cited in doc.paths:
            # Only source files. Generated snapshots are rewritten every run,
            # so comparing against them makes every ADR look permanently stale
            # -- the exact noise that teaches readers to ignore a report.
            if not cited.endswith(".py"):
                continue
            cited_date = dates.get(cited)
            if not cited_date or cited_date <= doc_date:
                continue
            days = _days_between(doc_date, cited_date)
            if newest is None or days > newest[0]:
                newest = (days, cited)
        if newest:
            ranked.append((newest[0], doc.path, newest[1]))
    return sorted(ranked, key=lambda row: (-row[0], row[1]))


def _days_between(earlier: str, later: str) -> int:
    from datetime import date

    return (date.fromisoformat(later) - date.fromisoformat(earlier)).days


def render_health(
    facts: list[Facts],
    issues: list[Issue],
    allowed: dict[str, str],
    verdicts: dict[str, str],
    ledger: list[dict[str, Any]],
    decisions: list[dict[str, Any]],
    decision_issues: list[str],
    mentions: dict[str, list[str]],
    adr_total: int,
    gate_count: int,
) -> str:
    grade_count = {"empirical": 0, "referential": 0, "narrative": 0}
    for doc in facts:
        grade_count[evidence_grade(doc, verdicts)] += 1
    with_experiment = sum(1 for doc in facts if doc.experiments)
    with_anchor = sum(1 for doc in facts if measurement_anchors(doc))
    live = [issue for issue in issues if f"{issue.doc}::{issue.token}" not in allowed]
    waived = len(issues) - len(live)
    open_rows = [row for row in ledger if row.get("verdict") == "open"]
    undecided = [row for row in ledger if row.get("verdict") not in {"confirmed", "refuted", "partial", "open"}]
    unmentioned = [code for code, docs in mentions.items() if not docs]
    # A decision that leans on an experiment later refuted is the case this
    # whole index exists for.
    cited_refuted = refuted_dependencies(decisions, verdicts)

    lines = [
        GENERATED_MARK + " health -->",
        GENERATED_NOTE,
        "",
        "# 知识库健康度",
        "",
        "回答三个问题：哪些引用已经指向不存在的东西、每条结论靠什么站住、"
        "哪些猜测还没有被检验。指标口径见 [kb.md](kb.md)。",
        "",
        "## 概览",
        "",
        "| 项 | 值 |",
        "| --- | ---: |",
        f"| 参与统计的文档 | {len(facts)} |",
        f"| 引用失效 | **{len(live)}**（另有 {waived} 处登记豁免） |",
        "| 证据类型：实证 / 可复核 / 纯叙述 | "
        f"{grade_count['empirical']} / {grade_count['referential']} / {grade_count['narrative']} |",
        f"| 引用实验编号的文档 | {with_experiment} |",
        f"| 引用测量脚本或快照的文档 | {with_anchor} |",
        f"| 实验台账 | {len(ledger)} 条，其中未结 {len(open_rows)} 条 |",
        f"| 决策索引 | {len(decisions)}/{adr_total} 份 ADR |",
        f"| 无文档解释的规则 | {len(unmentioned)}/{len(mentions)} |",
        f"| CI 门禁 | {gate_count} 道 |",
        "",
    ]

    lines += ["## 引用失效", ""]
    if live:
        lines += ["| 文档 | 引用 | 类型 | 原因 |", "| --- | --- | --- | --- |"]
        lines += [f"| `{i.doc}` | `{i.token}` | {i.kind} | {i.detail} |" for i in live]
        lines += ["", "修复方式：改引用，或在 `docs/kb-allow.json` 登记并写清为什么保留。", ""]
    else:
        lines += ["没有失效引用。", ""]

    if allowed:
        lines += ["### 已登记豁免", ""]
        lines += [f"- `{key}` —— {reason}" for key, reason in sorted(allowed.items())]
        stale = unused_waivers(allowed, issues)
        if stale:
            lines += ["", "以下豁免已不匹配任何失效引用，可以删除：", ""]
            lines += [f"- `{key}`" for key in stale]
        lines += [""]

    lines += ["## 证据类型", ""]
    lines += [
        "| 类型 | 含义 | 数量 |",
        "| --- | --- | ---: |",
        f"| 实证 | 引用了已结案的实验，结论可回溯到产物 | {grade_count['empirical']} |",
        f"| 可复核 | 引用了存在的代码或文件 | {grade_count['referential']} |",
        f"| 纯叙述 | 没有机械可核验的锚点 | {grade_count['narrative']} |",
        "",
    ]
    narrative = sorted(doc.path for doc in facts if evidence_grade(doc, verdicts) == "narrative")
    if narrative:
        lines += ["纯叙述文档（不等于错，但不能自动复核）：", ""]
        lines += [f"- `{path}`" for path in narrative[:20]]
        if len(narrative) > 20:
            lines.append(f"- …另有 {len(narrative) - 20} 份")
        lines.append("")

    lines += ["## 实验台账", ""]
    if undecided:
        lines += ["以下记录的 `verdict` 不在允许集合内：", ""]
        lines += [f"- `{row.get('id')}`: {row.get('verdict')!r}" for row in undecided]
        lines.append("")
    unjudgeable: list[tuple[str, str]] = []
    for row in ledger:
        ident = str(row.get("id"))
        if row.get("verdict") == "open" and not row.get("metric"):
            unjudgeable.append((ident, "未结且没有 metric，跑完也不知道填什么"))
        if "或" in str(row.get("expect", "")):
            unjudgeable.append((ident, "expect 里含「或」：两个可能指标等于没有指标"))
    if unjudgeable:
        lines += ["无法判定的记录（写法问题，不是数据问题）：", ""]
        lines += [f"- `{ident}`: {reason}" for ident, reason in unjudgeable]
        lines.append("")
    if open_rows:
        lines += ["未结项（有 prediction，还没有结论）：", ""]
        lines += [f"- `{row['id']}` {row['question']}" for row in open_rows]
        lines.append("")
    if not open_rows and not undecided:
        lines += ["台账里没有未结项。", ""]

    lines += ["## 决策索引", ""]
    if decision_issues:
        lines += ["结构问题：", ""]
        lines += [f"- {problem}" for problem in decision_issues]
        lines.append("")
    if decisions:
        lines += [
            f"已索引 {len(decisions)} / {adr_total} 份 ADR（{len(decisions) / max(adr_total, 1):.0%}）。"
            "未索引的 ADR 不是错的，只是还没有写出「什么情况下该推翻它」。",
            "",
            "| 决策 | ADR | 依据 | 案例 | 状态 |",
            "| --- | --- | --- | --- | --- |",
        ]
        lines += [
            f"| {row['id']} | `{row['adr']}` | "
            + (", ".join(f"`{item}`" for item in row.get("evidence") or []) or "—")
            + " | "
            + (", ".join(f"`{item}`" for item in row.get("examples") or []) or "—")
            + f" | {row.get('status')} |"
            for row in decisions
        ]
        lines.append("")
    else:
        lines += ["还没有决策索引。`docs/decisions.jsonl` 为空时这份报告只统计引用与实验。", ""]

    if cited_refuted:
        lines += ["### 依据已被推翻的决策", ""]
        lines += [
            f"- `{decision_id}`（{adr}）引用 `{experiment}`，该实验结论为 refuted"
            for decision_id, adr, experiment in cited_refuted
        ]
        lines += ["", "这些决策要么改主意，要么在正文里说明为什么推翻之后仍然成立。", ""]

    lines += ["## 规则覆盖", ""]
    if unmentioned:
        lines += ["以下规则没有任何文档解释（代码里有，文字里没有）：", ""]
        lines += [f"- `{code}`" for code in unmentioned]
        lines.append("")
    else:
        lines += ["每条规则至少被一份文档提到。", ""]
    thin = sorted((code, docs) for code, docs in mentions.items() if len(docs) == 1)
    if thin:
        lines += ["只被一份文档提到：" + "、".join(f"`{code}`" for code, _ in thin), ""]

    return "\n".join(lines).rstrip() + "\n"


def render_next(
    issues: list[Issue],
    allowed: dict[str, str],
    ledger: list[dict[str, Any]],
    decisions: list[dict[str, Any]],
    facts: list[Facts],
    all_facts: list[Facts],
    texts: dict[str, str],
    mentions: dict[str, list[str]],
) -> str:
    live = [issue for issue in issues if f"{issue.doc}::{issue.token}" not in allowed]
    open_rows = [row for row in ledger if row.get("verdict") == "open"]
    verdicts = {str(row.get("id")): str(row.get("verdict")) for row in ledger}
    refuted_decisions = [
        (row.get("id"), item)
        for row in decisions
        for item in row.get("evidence") or []
        if verdicts.get(item) == "refuted"
    ]
    narrative = [doc for doc in facts if evidence_grade(doc, verdicts) == "narrative"]
    unmentioned = [code for code, docs in mentions.items() if not docs]

    lines = [
        GENERATED_MARK + " next -->",
        GENERATED_NOTE,
        "",
        "# 下一步队列",
        "",
        "按「能不能机械判定」分层，不按感觉排序。每一条都写了怎么消掉。",
        "",
    ]

    lines += ["## P0 · 已经坏了", ""]
    if live:
        lines += [f"- [ ] `{i.doc}` 的 `{i.token}`：{i.detail}" for i in live]
    else:
        lines += ["没有。"]
    lines.append("")

    lines += ["## P1 · 依据被自己推翻", ""]
    if refuted_decisions:
        lines += [
            f"- [ ] 决策 `{decision_id}` 引用的 `{experiment}` 已被推翻：改决策，或写清为什么仍然成立"
            for decision_id, experiment in refuted_decisions
        ]
    if open_rows:
        lines += [f"- [ ] 结掉 `{row['id']}`：{row['question']}" for row in open_rows]
    if not refuted_decisions and not open_rows:
        lines += ["没有。"]
    lines.append("")

    lines += ["## P2 · 重要但没有证据锚点", ""]
    # Rank by how many other documents lean on it; a long tail would bury the
    # few that matter and teach the reader to skip this section.
    linked = incoming_links(all_facts)
    important = [doc for doc in narrative if linked.get(doc.path, 0) >= 2]
    important.sort(key=lambda d: (-linked.get(d.path, 0), d.path))
    indexed_adrs = {str(row.get("adr")) for row in decisions}
    if important:
        lines += [
            f"被引用最多的一批（共 {len(important)} 份）。ADR 缺的是失效条件，"
            "报告缺的是代码或数据锚点——两类欠账的补法不同。",
            "",
        ]
        for doc in important[:8]:
            if doc.kind == "adr" and doc.path not in indexed_adrs:
                lines.append(
                    f"- [ ] `{doc.path}` 被 {linked[doc.path]} 份文档引用，"
                    "但没写「什么情况下该推翻」（`docs/decisions.jsonl`）"
                )
                continue
            body = texts.get(doc.path, "")
            hint = ""
            # An ADR quoting a measurement is normal; a guide quoting one and
            # citing nothing is the case worth flagging. Stated as an
            # observation, not a diagnosis: measurement.md is about method and
            # uses the same words, so the marker can only say "this text talks
            # about results", not "someone forgot to log an experiment".
            if doc.kind in {"guide", "snapshot"} and any(
                marker in body for marker in ("实测", "通过率", "P50", "P95", "均分", "样本")
            ):
                hint = " —— 正文含实测数字，但没有编号或数据锚点"
            lines.append(f"- [ ] `{doc.path}` 被 {linked[doc.path]} 份文档引用{hint}")
        if len(important) > 8:
            lines.append(f"- 其余 {len(important) - 8} 份见 `docs/kb-health.md`")
    else:
        lines += ["没有。"]
    lines.append("")

    lines += ["## P3 · 文字里缺的规则", ""]
    if unmentioned:
        lines += [f"- [ ] `{code}` 在代码里生效，但没有任何文档解释它" for code in unmentioned]
    else:
        lines += ["没有。"]
    lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def render_handoff(
    facts: list[Facts],
    issues: list[Issue],
    allowed: dict[str, str],
    ledger: list[dict[str, Any]],
    decisions: list[dict[str, Any]],
    adr_total: int,
    gate_count: int,
) -> str:
    live = [issue for issue in issues if f"{issue.doc}::{issue.token}" not in allowed]
    open_rows = [row for row in ledger if row.get("verdict") == "open"]
    refuted = sum(1 for row in ledger if row.get("verdict") == "refuted")
    decided = sum(1 for row in ledger if row.get("verdict") in {"confirmed", "refuted", "partial"})

    settled = "全部已结" if decided == len(ledger) else f"已结 {decided} 条"
    lines = [
        GENERATED_MARK + " handoff -->",
        GENERATED_NOTE,
        "",
        "# 交接：从这里接",
        "",
        "这份文件过去是手写的，写了「27 道门禁、68 个地点」，隔天就错了。"
        "现在它由脚本生成，数字与仓库同源，不会再漂。",
        "",
        "## 现在是什么状态",
        "",
        "| 项 | 值 |",
        "| --- | ---: |",
        f"| CI 门禁 | {gate_count} 道 |",
        f"| 文档 | {len(facts)} 份（ADR {adr_total} 份） |",
        f"| 实验台账 | {len(ledger)} 条，{settled}，推翻 {refuted} 条 |",
        f"| 未结实验 | {len(open_rows)} 条 |",
        f"| 决策索引 | {len(decisions)} / {adr_total} 份 ADR |",
        f"| 引用失效 | {len(live)} 处 |",
        "",
        "## 先读什么",
        "",
        "1. 这份交接（当前页）→ 知道规模与状态。",
        "2. [next.md](next.md) → 知道下一步做什么，按 P0–P3 分层。",
        "3. [kb-health.md](kb-health.md) → 知道每条结论靠什么站住。",
        "4. [README.md](../README.md) → 知道项目在做什么。",
        "5. [experiments.md](experiments.md) → 知道哪些猜测已经被证伪。",
        "",
        "## 判断一个说法可不可信",
        "",
        "查三件事，都能在仓库里完成：",
        "",
        "- 它引用的代码还在吗（`kb-health.md` 的「引用失效」）。",
        "- 它的结论有没有实验编号（`E01` 这种，可在 `evals/experiments.jsonl` 查到预测与结论）。",
        "- 支撑它的实验是被确认还是被推翻（`experiments.md` 的判定列）。",
        "",
        "三样都没有的段落，是推断，不是测量。这不代表它错，但不要当成已验证的事实往下建。",
        "",
        "## 不要做什么",
        "",
        "- 不要手改这份文件，也不要手改 `kb-health.md` 与 `next.md`；改完数据重跑 `--write`。",
        "- 不要在历史报告里追着改过期引用：那是当时的证据。新写的内容引用当前代码。",
        "- 不要为了让门禁变绿而删掉实验的 `refuted` 记录。",
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def gate_count() -> int:
    text = (ROOT / "Makefile").read_text(encoding="utf-8")
    match = re.search(r"^gates:\s*\n((?:\t.*\n)+)", text, re.MULTILINE)
    if not match:
        return 0
    return sum(1 for line in match.group(1).splitlines() if line.strip().startswith("$(PYTHON)"))


def load_allow() -> tuple[dict[str, str], list[str]]:
    """Waivers, keyed by `doc::token`, each carrying the reason it exists.

    A waiver without a reason is a deletion with extra steps, so the reason is
    rendered next to it rather than kept in a side file nobody reads.
    """
    path = DOCS / "kb-allow.json"
    if not path.exists():
        return {}, []
    rows = json.loads(path.read_text(encoding="utf-8"))
    keys: dict[str, str] = {}
    problems: list[str] = []
    for row in rows:
        key = f"{row.get('doc')}::{row.get('token')}"
        reason = str(row.get("reason") or "")
        if not reason:
            problems.append(f"{key}: 豁免必须写 reason")
        keys[key] = reason
    return keys, problems


def normalize(text: str) -> str:
    return text.replace("\r\n", "\n").strip()


def next_decision_id(rows: list[dict[str, Any]]) -> str:
    used = [
        int(str(row["id"])[1:])
        for row in rows
        if str(row.get("id", ""))[:1] == "D" and str(row["id"])[1:].isdigit()
    ]
    return f"D{max(used, default=0) + 1:02d}"


def append_decision(
    args: argparse.Namespace,
    decisions: list[dict[str, Any]],
    adrs: set[str],
    experiment_ids: set[str],
    path: Path = DECISIONS,
) -> tuple[int, str]:
    """Add a decision the way the experiment ledger adds a prediction.

    The refusals are the point. An ADR with no revisit trigger is a decision
    nobody can overturn on evidence, and a trigger phrased as a feeling is the
    same thing in different words -- so both are rejected here, at the moment of
    writing, instead of being flagged in a report read a week later.
    """
    if args.adr not in adrs:
        print(f"ADR 不存在：{args.adr or '<empty>'}", file=sys.stderr)
        return 2, ""
    if not args.decision.strip():
        print("必须给 --decision：一句话说清选了什么", file=sys.stderr)
        return 2, ""
    if not args.breaks_if:
        print("必须给至少一条 --breaks-if：没有失效条件的决策无法被推翻", file=sys.stderr)
        return 2, ""
    for trigger in args.breaks_if:
        if len(trigger.strip()) < 8:
            print(f"失效条件太短，无法判断：{trigger!r}", file=sys.stderr)
            return 2, ""
        if any(word in trigger for word in VAGUE_TRIGGERS):
            print(f"失效条件不像可观测事件：{trigger!r}", file=sys.stderr)
            return 2, ""

    row: dict[str, Any] = {
        "id": next_decision_id(decisions),
        "adr": args.adr,
        "decision": args.decision.strip(),
        "evidence": list(dict.fromkeys(args.evidence)),
        "breaks_if": [item.strip() for item in args.breaks_if],
        "status": "active",
        "reviewed": dt.date.today().isoformat(),
    }
    examples = list(dict.fromkeys(args.examples))
    if examples:
        row["examples"] = examples
    if args.note.strip():
        row["note"] = args.note.strip()

    problems = decision_problems([row], adrs, experiment_ids)
    if problems:
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 2, ""

    decisions.append(row)
    path.write_text(
        "\n".join(json.dumps(item, ensure_ascii=False) for item in decisions) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return 0, str(row["id"])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="knowledge-base health, queue and handoff")
    parser.add_argument("--write", action="store_true", help="regenerate the three pages")
    parser.add_argument("--check", action="store_true", help="verify citations, decisions and page freshness")
    parser.add_argument("--queue", action="store_true", help="print the local drift ranking (needs full git history)")
    parser.add_argument("--why", metavar="PATH", default="", help="who depends on this file, and what to reconsider")
    parser.add_argument("--decide", action="store_true", help="append a decision with its revisit trigger")
    parser.add_argument("--adr", default="", help="the ADR this decision indexes")
    parser.add_argument("--decision", default="", help="the choice, in one sentence")
    parser.add_argument("--breaks-if", action="append", default=[], help="observable event that should reopen it")
    parser.add_argument("--evidence", action="append", default=[], help="experiment id that supports it")
    parser.add_argument("--examples", action="append", default=[], help="experiment id cited as a case")
    parser.add_argument("--note", default="", help="anything a reader needs that the fields cannot hold")
    args = parser.parse_args(argv)

    try:
        sys.path.insert(0, str(SRC))
        from shotplan.domain.constraints import RULES
    except Exception as exc:  # pragma: no cover - import guarded for a clear message
        print(f"cannot import RULES from the package: {exc}", file=sys.stderr)
        return 1

    paths = all_docs()
    texts = {rel(path): path.read_text(encoding="utf-8") for path in paths}
    all_facts = [read_facts(path, texts[rel(path)]) for path in paths]
    # Generated pages describe the data rather than adding to it; counting them
    # as "documents without evidence" would be measuring the ruler.
    facts = [fact for fact in all_facts if fact.kind != "generated"]
    decisions = load_jsonl(DECISIONS) if DECISIONS.exists() else []
    ledger = load_jsonl(LEDGER)
    facts = enrich(facts, decisions, ledger)
    verdicts = {str(row["id"]): str(row["verdict"]) for row in ledger}
    experiment_ids = set(verdicts)
    symbols = symbol_index()
    names = set(symbols)
    adrs = {rel(path) for path in (DOCS / "adr").glob("*.md")}

    if args.why:
        print(explain(args.why, facts, decisions, ledger, symbols, texts))
        return 0

    if args.decide:
        code, new_id = append_decision(args, decisions, adrs, experiment_ids)
        if code != 0:
            return code
        print(f"{new_id} 已登记")
        # Writing a decision and regenerating the pages are one action; going
        # through the normal entry point keeps that guarantee in one place.
        return main(["--write"])

    issues = cite_issues(facts, names, experiment_ids)
    allowed, allow_problems = load_allow()
    d_problems = decision_problems(decisions, adrs, experiment_ids)
    mentions = rule_mentions(texts, [str(rule["code"]) for rule in RULES])
    gates = gate_count()

    health = render_health(
        facts, issues, allowed, verdicts, ledger, decisions, d_problems, mentions, len(adrs), gates
    )
    nxt = render_next(issues, allowed, ledger, decisions, facts, all_facts, texts, mentions)
    handoff = render_handoff(facts, issues, allowed, ledger, decisions, len(adrs), gates)

    if args.queue:
        dates = commit_dates()
        if not dates:
            print("没有可用的 git 历史（浅克隆？），跳过漂移排序。")
        else:
            print("漂移最大（引用的代码在文档之后改动过）：")
            for days, doc, cited in drift_rank(facts, dates)[:15]:
                print(f"  {days:4d} 天  {doc}  ->  {cited}")
        return 0

    if args.write:
        for path, content in ((HEALTH, health), (NEXT, nxt), (HANDOFF, handoff)):
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {rel(path)} ({len(content.splitlines())} lines)")

    live = [issue for issue in issues if f"{issue.doc}::{issue.token}" not in allowed]
    problems: list[str] = []
    problems += [f"citation: {i.doc} -> {i.token} ({i.detail})" for i in live]
    problems += [f"decisions: {p}" for p in d_problems]
    problems += [f"allow: {p}" for p in allow_problems]
    for path, content in ((HEALTH, health), (NEXT, nxt), (HANDOFF, handoff)):
        if not path.exists():
            problems.append(f"{rel(path)}: 缺少生成页，运行 --write")
        elif normalize(path.read_text(encoding="utf-8")) != normalize(content):
            problems.append(f"{rel(path)}: 与数据不一致，运行 --write")

    print(
        f"kb: {len(facts)} docs, {len(live)} live citation issue(s), "
        f"{len(decisions)} decision(s), {len(ledger)} experiment(s), {gates} gate(s)"
    )
    for warning in vague_triggers(decisions):
        print(f"  WARN 空的失效条件: {warning}", file=sys.stderr)
    if problems:
        for problem in problems:
            print(f"  FAIL {problem}", file=sys.stderr)
        return 1
    print("kb gate: OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
