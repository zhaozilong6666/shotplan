"""Make the record-keeping measure itself, so it cannot rot silently.

The repository already gates what it produces: eval reports, gate counts,
knowledge freshness, README numbers. What nothing gates is the **record of why
those things are true** -- 60+ documents that cite code, experiments and each
other, and 18 ADRs whose reasoning is only prose.

Two failure modes motivated this script, both observed here rather than
imagined:

1. `docs/HANDOFF.md` was written by hand to say "27 gates, 68 locations". One
   day later it said 30 and 67. A hand-written status document is stale the
   moment it is committed; the only fix that lasts is generating it.
2. `docs/optimization-report.md` cites `_source_ref_exists()` and `_flatten()`.
   Both functions were removed. Nothing noticed, because a backticked name is
   invisible to the link checker and to the type checker.

The design follows two findings from the literature. First, document age is a
weak signal: stable systems produce old-and-correct pages, so ranking by age
trains readers to ignore the report. What predicts rot is divergence -- code
moving while the document describing it stands still. Second, reference rot is
mechanically checkable while "is this still true?" is not, so only the former
is allowed to fail the build; everything else is ranked and left for a human.

    python scripts/kb.py --write     # regenerate docs/kb-health.md, docs/next.md, docs/HANDOFF.md
    python scripts/kb.py --check     # CI: citations resolve, decisions are well formed, pages current
    python scripts/kb.py --queue     # local only: worst drift first, needs full git history

Deterministic by construction: no timestamps, no git hashes, no absolute paths
in the rendered pages, so a shallow CI clone and a full local clone agree.
"""

